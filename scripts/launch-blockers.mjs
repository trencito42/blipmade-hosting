#!/usr/bin/env node
/**
 * Lists what the operator still has to write before the platform is launched.
 *
 * The legal documents carry a marker, `TODO(operator): ...`, wherever a fact is needed that
 * only the operator knows: the legal name, the contact addresses, the periods and the
 * figures of the policies. The platform never invents them. This script finds every marker
 * and writes the list, so the blockers are one document and nothing is lost in the pages.
 *
 * Usage:
 *   node scripts/launch-blockers.mjs            # prints the list
 *   node scripts/launch-blockers.mjs --write    # writes docs/LAUNCH-BLOCKERS.md
 *   node scripts/launch-blockers.mjs --check    # exits with 1 while a marker is left
 */
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = process.env.ROOT ?? join(dirname(fileURLToPath(import.meta.url)), '..');
const SKIP = new Set(['node_modules', 'dist', '.git', 'tests']);
const MARKER = /TODO\(operator\):\s*([^"'`<>{}]+?)(?=["'`<>{}]|$)/g;

async function* files(directory) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    if (SKIP.has(entry.name)) continue;
    const full = join(directory, entry.name);
    if (entry.isDirectory()) yield* files(full);
    else if (/\.(tsx?|md|json)$/.test(entry.name) && !/launch-blockers/i.test(entry.name)) yield full;
  }
}

const found = [];
for (const base of ['web/src', 'api/src', 'docs']) {
  const directory = join(ROOT, base);
  try {
    for await (const file of files(directory)) {
      const text = await readFile(file, 'utf-8');
      for (const match of text.matchAll(MARKER)) {
        const line = text.slice(0, match.index).split('\n').length;
        found.push({ file: relative(ROOT, file), line, what: match[1].trim().replace(/\s+/g, ' ') });
      }
    }
  } catch {
    /* a folder that is not there has nothing to list */
  }
}

// The same fact is asked for in many places: list it once, with every place it is needed.
const byFact = new Map();
for (const item of found) {
  const entry = byFact.get(item.what) ?? [];
  entry.push(`${item.file}:${item.line}`);
  byFact.set(item.what, entry);
}

const lines = [
  '# Launch blockers: what only the operator can write',
  '',
  'The legal documents carry a marker where a fact is needed that the platform does not know and must not invent.',
  `There are ${byFact.size} different facts missing, in ${found.length} places. The launch is not approved while any of them is open.`,
  '',
  'Generated by `scripts/launch-blockers.mjs`. Fill the text in the page (`web/src/legal/documents/`) and run the script again.',
  '',
];
for (const [what, places] of [...byFact.entries()].sort()) {
  lines.push(`## ${what}`, '', ...places.map((place) => `- \`${place}\``), '');
}
const out = lines.join('\n');

if (process.argv.includes('--write')) {
  await writeFile(join(ROOT, 'docs/LAUNCH-BLOCKERS.md'), out);
  console.log(`wrote docs/LAUNCH-BLOCKERS.md: ${byFact.size} facts, ${found.length} places`);
} else {
  console.log(out);
}
if (process.argv.includes('--check') && found.length) process.exit(1);
